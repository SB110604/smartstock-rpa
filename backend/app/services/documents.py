"""Purchase-document PDFs (ReportLab): purchase order, goods receipt note, debit note."""

import io
from datetime import date
from pathlib import Path
from typing import Any

from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.units import mm
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle

from app.core.config import settings as env
from app.services import gst
from app.services.pdfbase import BRAND, HEAD_BG, LINE, amount_in_words, fonts, inr, styles


def _d(v: date | None) -> str:
    return v.strftime("%d-%m-%Y") if v else "—"


def _header(business: dict[str, Any], title: str, meta: list[tuple[str, str]]) -> list[Any]:
    st = styles()
    left = [Paragraph(business.get("name") or "", st["title"]),
            Paragraph(", ".join(x for x in (business.get("address"), business.get("city"), business.get("state")) if x),
                      st["small"]),
            Paragraph(f"GSTIN: {business.get('gstin') or '—'} · {business.get('phone') or ''} · {business.get('email') or ''}",
                      st["small"])]
    right = [Paragraph(f"<b>{title}</b>", st["h2"])] + [Paragraph(f"{k}: <b>{v}</b>", st["body"]) for k, v in meta]
    t = Table([[left, right]], colWidths=[110 * mm, 70 * mm])
    t.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"), ("LINEBELOW", (0, 0), (-1, 0), 1.2, BRAND),
                           ("BOTTOMPADDING", (0, 0), (-1, -1), 6)]))
    return [t, Spacer(1, 6)]


def _party(label: str, supplier: Any) -> Table:
    st = styles()
    rows = [Paragraph(f"<b>{label}</b>", st["bold"]), Paragraph(supplier.name, st["body"]),
            Paragraph(supplier.address or "", st["small"]),
            Paragraph(f"State: {supplier.state} · GSTIN: {supplier.gstin or 'Unregistered'}", st["small"]),
            Paragraph(f"{supplier.contact_name or ''} {supplier.phone or ''} {supplier.email or ''}", st["small"])]
    t = Table([[rows]], colWidths=[180 * mm])
    t.setStyle(TableStyle([("BOX", (0, 0), (-1, -1), 0.5, LINE), ("BACKGROUND", (0, 0), (-1, -1), colors.white)]))
    return t


def _grid(data: list[list[Any]], widths: list[float], right_cols: set[int], total_rows: int = 0) -> Table:
    regular, bold = fonts()
    t = Table(data, colWidths=widths, repeatRows=1)
    style = [
        ("FONT", (0, 0), (-1, -1), regular, 8), ("FONT", (0, 0), (-1, 0), bold, 8),
        ("BACKGROUND", (0, 0), (-1, 0), HEAD_BG), ("GRID", (0, 0), (-1, -1), 0.4, LINE),
        ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
    ]
    for c in right_cols:
        style.append(("ALIGN", (c, 0), (c, -1), "RIGHT"))
    if total_rows:
        style += [("FONT", (0, -total_rows), (-1, -1), bold, 8), ("BACKGROUND", (0, -total_rows), (-1, -1), HEAD_BG)]
    t.setStyle(TableStyle(style))
    return t


def _build(story: list[Any], title: str) -> bytes:
    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, leftMargin=15 * mm, rightMargin=15 * mm, topMargin=12 * mm,
                            bottomMargin=12 * mm, title=title, author="SmartStock RPA")
    regular, _ = fonts()

    def footer(canvas: Any, d: Any) -> None:
        canvas.setFont(regular, 7)
        canvas.setFillColorRGB(0.4, 0.45, 0.5)
        canvas.drawString(15 * mm, 8 * mm, f"{title} · generated by SmartStock RPA")
        canvas.drawRightString(A4[0] - 15 * mm, 8 * mm, f"Page {d.page}")

    doc.build(story, onFirstPage=footer, onLaterPages=footer)
    return buf.getvalue()


def purchase_order_pdf(po: Any, business: dict[str, Any], terms: str) -> bytes:
    st = styles()
    inter = po.is_interstate
    story = _header(business, "PURCHASE ORDER", [("PO No", po.po_no), ("Date", _d(po.order_date)),
                                                 ("Deliver by", _d(po.expected_date)), ("Deliver to", po.location.name)])
    story += [_party("Supplier", po.supplier), Spacer(1, 6)]
    head = ["#", "Item", "HSN", "Qty", "Rate", "Taxable", "GST %"] + (["IGST"] if inter else ["CGST", "SGST"]) + ["Amount"]
    rows: list[list[Any]] = [head]
    for i, ln in enumerate(po.lines, start=1):
        t = gst.line_tax(ln.qty, ln.unit_price, ln.gst_rate, inter)
        tax_cols = [inr(t.igst)] if inter else [inr(t.cgst), inr(t.sgst)]
        rows.append([i, Paragraph(f"{ln.product.name}<br/><font size=6.5 color='#64748b'>{ln.product.sku}</font>", st["body"]),
                     ln.hsn_code or ln.product.hsn_code or "", f"{ln.qty:g} {ln.product.unit}", inr(ln.unit_price),
                     inr(t.taxable), f"{ln.gst_rate:g}", *tax_cols, inr(t.total)])
    tax_tot = [inr(po.igst)] if inter else [inr(po.cgst), inr(po.sgst)]
    rows.append(["", "Total", "", "", "", inr(po.subtotal), "", *tax_tot, inr(po.total)])
    widths = [7, 55, 14, 18, 18, 22, 11] + ([18] if inter else [16, 16]) + [22]
    story.append(_grid(rows, [w * mm for w in widths], set(range(3, len(head))), total_rows=1))
    story += [Spacer(1, 4), Paragraph(f"<b>Amount in words:</b> {amount_in_words(po.total)}", st["body"])]
    summary = gst.rate_summary([(ln.qty, ln.unit_price, ln.gst_rate) for ln in po.lines], inter)
    srows = [["GST slab", "Taxable value", *(["IGST"] if inter else ["CGST", "SGST"])]]
    for s in summary:
        srows.append([f"{s['rate']:g}%", inr(s["taxable"]), *([inr(s["igst"])] if inter else [inr(s["cgst"]), inr(s["sgst"])])])
    story += [Spacer(1, 6), Paragraph("Tax summary" + (" (inter-state: IGST)" if inter else " (intra-state: CGST + SGST)"),
                                      st["bold"]),
              _grid(srows, [30 * mm, 40 * mm] + [35 * mm] * (1 if inter else 2), {1, 2, 3})]
    portal = f"{env.FRONTEND_URL}/portal/orders/{po.id}"
    story += [Spacer(1, 8), Paragraph("Terms &amp; conditions", st["bold"])]
    story += [Paragraph(line, st["small"]) for line in (terms or "").splitlines() if line.strip()]
    story += [Spacer(1, 6), Paragraph(f"Confirm this order and share dispatch details in the supplier portal: {portal}",
                                      st["small"]),
              Spacer(1, 18), Paragraph(f"For {business.get('name')}<br/><br/>Authorised signatory", st["right"])]
    return _build(story, po.po_no)


def grn_pdf(grn: Any, po: Any, business: dict[str, Any]) -> bytes:
    st = styles()
    story = _header(business, "GOODS RECEIPT NOTE", [("GRN No", grn.grn_no), ("Date", _d(grn.received_at.date())),
                                                     ("PO No", po.po_no)])
    story += [_party("Supplier", po.supplier), Spacer(1, 6)]
    rows: list[list[Any]] = [["#", "Item", "Batch", "Expiry", "Received", "Damaged"]]
    for i, ln in enumerate(grn.lines, start=1):
        rows.append([i, Paragraph(ln.product.name, st["body"]), ln.batch_no, _d(ln.expiry_date), f"{ln.received_qty:g}",
                     f"{ln.damaged_qty:g}"])
    story.append(_grid(rows, [8 * mm, 72 * mm, 32 * mm, 24 * mm, 22 * mm, 22 * mm], {4, 5}))
    if grn.note:
        story += [Spacer(1, 6), Paragraph(f"Note: {grn.note}", st["body"])]
    return _build(story, grn.grn_no)


def debit_note_pdf(ret: Any, business: dict[str, Any], interstate: bool) -> bytes:
    st = styles()
    story = _header(business, "DEBIT NOTE", [("Debit note", ret.debit_note_no or "—"), ("Return No", ret.return_no),
                                             ("Date", _d(ret.created_at.date()))])
    story += [_party("Debit to", ret.supplier), Spacer(1, 6)]
    head = ["#", "Item", "Qty", "Rate", "Taxable", "GST %", "Tax", "Amount", "Reason"]
    rows: list[list[Any]] = [head]
    for i, ln in enumerate(ret.lines, start=1):
        t = gst.line_tax(ln.qty, ln.unit_price, ln.gst_rate, interstate)
        rows.append([i, Paragraph(ln.product.name, st["body"]), f"{ln.qty:g}", inr(ln.unit_price), inr(t.taxable),
                     f"{ln.gst_rate:g}", inr(t.tax), inr(t.total), ln.reason or ""])
    rows.append(["", "Total", "", "", inr(ret.subtotal), "", inr(ret.tax), inr(ret.total), ""])
    story.append(_grid(rows, [w * mm for w in (7, 55, 13, 18, 20, 11, 17, 20, 19)], {2, 3, 4, 5, 6, 7}, total_rows=1))
    story += [Spacer(1, 4), Paragraph(f"<b>Amount in words:</b> {amount_in_words(ret.total)}", st["body"]),
              Spacer(1, 4), Paragraph(f"Reason: {ret.reason or 'Goods returned'}", st["body"]),
              Paragraph("Please issue a credit note for the above amount.", st["small"])]
    return _build(story, ret.debit_note_no or ret.return_no)


def save(kind: str, name: str, data: bytes) -> str:
    folder: Path = env.storage_subdir(kind)
    path = folder / f"{name}.pdf"
    path.write_bytes(data)
    return str(path)
